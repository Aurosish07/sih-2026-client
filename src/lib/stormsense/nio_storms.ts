function makeTP(
  timestamp: string,
  lat: number,
  lon: number,
  wind_kt: number,
  pressure_hpa: number,
  direction: string,
  speed: number,
  forecast = false,
): TrackPoint {
  return {
    id: `${timestamp}-${lat}-${lon}`,
    timestamp,
    lat,
    lon,
    wind_kt,
    pressure_hpa,
    movement_direction: direction,
    movement_speed: speed,
    source: "nio/historical",
    category: windToCategory(wind_kt),
    forecast,
    windSpeed: wind_kt,
    pressure: pressure_hpa,
    nature: windToCategory(wind_kt),
    stormSpeed: speed,
    stormDir: 0,
  };
}

function makeOB(
  timestamp: string,
  lat: number,
  lon: number,
  wind_kt: number,
  pressure_hpa: number,
  direction: string,
  speed: number,
  distance_to_land_km: number,
  satellite_hint: string,
): Observation {
  return {
    id: `${timestamp}-${lat}-${lon}`,
    timestamp,
    lat,
    lon,
    wind_kt,
    pressure_hpa,
    movement_direction: direction,
    movement_speed: speed,
    distance_to_land_km,
    source: "nio/historical",
    satellite_hint,
    windSpeed: wind_kt,
    pressure: pressure_hpa,
    nature: windToCategory(wind_kt),
    distanceToLand: distance_to_land_km,
    stormSpeed: speed,
    stormDir: 0,
  };
}
